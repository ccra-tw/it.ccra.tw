// 鎖住批次並確認仍是草稿（大沈 R-itsu-1112-01 P1：匯入、改批次與配號共用同一把列鎖，持鎖後再核對狀態）。須在交易內呼叫。
function rcpt_lock_draft(PDO $d, int $batchId): array {
    if (!$d->inTransaction()) throw new LogicException('rcpt_lock_draft 要在交易內呼叫');
    $s = $d->prepare('SELECT * FROM batch WHERE id = ? FOR UPDATE');
    $s->execute([$batchId]);
    $b = $s->fetch(PDO::FETCH_ASSOC);
    if (!$b) throw new RuntimeException('找不到批次');
    if ($b['status'] !== 'draft') throw new RuntimeException('這個批次已經配號，清單已鎖定，不能再匯入或修改字軌、日期與產品明細');
    return $b;
}

// 資料庫錯誤只記 SQLSTATE，不記原始訊息（大沈 R-itsu-1112-01 P1：PostgreSQL 的 DETAIL 會帶整列資料＝捐物人個資）。
function rcpt_log_db_error(Throwable $e, string $where = ''): string {
    $code = $e instanceof PDOException ? (string)($e->errorInfo[0] ?? $e->getCode()) : get_class($e);
    $ref = substr(bin2hex(random_bytes(4)), 0, 8);
    error_log("it.ccra.tw receipt: db error ref=$ref sqlstate=$code" . ($where !== '' ? " at=$where" : ''));
    return $ref;
}

// 同一批名單裡重複的訂單編號（大沈 R-itsu-1112-01 P1：同檔兩列同訂單會各拿一張收據）。回傳 [order_no => 出現次數]
function rcpt_dup_in_batch(PDO $d, int $batchId): array {
    $s = $d->prepare("SELECT order_no, count(*) n FROM donation WHERE batch_id = ? AND order_no <> '' AND NOT void GROUP BY order_no HAVING count(*) > 1 ORDER BY order_no");
    $s->execute([$batchId]);
    return array_map('intval', $s->fetchAll(PDO::FETCH_KEY_PAIR));
}

// 民國年月日字串 115/09/14 ↔ 西元 date。接受 115/9/14、115-09-14、1150914。不合法回 null。
// 地址不完整就不寄（繁英姊 11/20 選 B：會被退件，自動設不寄＋標紅、可篩選）。
// 判準（她確認）：要有「路／街／大道」其中一個，且有「號」；巷、村里可有可無。
// 本來就不寄的資料（繁英姊 11/20：空白、「愛心捐贈」、「不用」、地址少於 4 個字）：不寄，但不算錯誤、不標紅
function rcpt_addr_nomail(string $addr, ?string $city = null): bool {
    // 繁英姊 11/20：沒有縣市（縣市欄空白、地址裡也沒有縣／市）＝根本不是地址（例如「祝天好心情~」），本來就不寄
    if ($city !== null && trim($city) === '' && !preg_match('/(縣|市)/u', $addr)) return true;
    // 繁英姊 11/20：連「路／街／大道／段／巷／弄／號」都沒有（例如店名「一木衛生行」），不是可修的地址，直接不寄、不用再確認
    if (!preg_match('/(路|街|大道|段|巷|弄|號)/u', $addr)) return true;
    $a = trim(preg_replace('/\s+/u', '', $addr));
    return $a === '' || $a === '空白' || mb_strpos($a, '愛心捐贈') !== false || mb_strpos($a, '不用') !== false || mb_strlen($a) < 4;
}
function rcpt_addr_incomplete(string $city, string $addr): bool {
    $s = $city . $addr;
    if (rcpt_addr_nomail($addr, $city)) return false;   // 本來就不寄的，不標紅（見上）
    if (preg_match('/信箱/u', $addr) && preg_match('/號/u', $addr)) return false;   // 繁英姊 11/20：郵政信箱沒有路名，有「號」就能寄（例：台北郵局第 12 號信箱、郵政 1234 號信箱）
    if (!preg_match('/(路|街|大道)/u', $s) || !preg_match('/號/u', $s)) return true;
    if (preg_match('/(路|街|段|巷|弄|號|樓|大道)\1/u', $addr)) return true;   // 繁英姊 11/20：「中山一路路204號」重複字也標紅
    return (bool)preg_match('/號.*(縣|市)/u', $addr);   // 繁英姊 11/20：「大義街16號新北市」門牌後面又接縣市，也要標紅讓她修
}
const RCPT_ADDR_NOTE = '地址不完整或有誤（缺路／街／大道、門牌號，或有重複字），自動不寄';
const RCPT_ADDR_NOTE_OLD = '地址不完整（缺路／街／大道或門牌號），自動不寄';   // 11/20 早上版本的說明文字，改好地址時一併清掉

function rcpt_roc_to_date(string $s): ?string {
    // 容錯（繁英姊 11/18 驗收）：全形數字與斜線、「115年11月18日」、民國前綴；也接受西元 YYYY-MM-DD（日曆欄位送來的）
    $s = trim(mb_convert_kana($s, 'as', 'UTF-8'));
    $s = str_replace(['／', '－', '．'], '/', $s);
    $s = preg_replace('/^民國\s*/u', '', $s);
    if (preg_match('/^(\d{2,3})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日?$/u', $s, $m)) $s = "$m[1]/$m[2]/$m[3]";
    if (preg_match('/^(\d{4})-(\d{2})-(\d{2})$/', $s, $m)) {
        [$y, $mo, $da] = [(int)$m[1], (int)$m[2], (int)$m[3]];
        return checkdate($mo, $da, $y) ? sprintf('%04d-%02d-%02d', $y, $mo, $da) : null;
    }
    if (preg_match('/^(\d{2,3})[\/\-.](\d{1,2})[\/\-.](\d{1,2})$/', $s, $m) || preg_match('/^(\d{3})(\d{2})(\d{2})$/', $s, $m)) {
        [$y, $mo, $da] = [(int)$m[1] + 1911, (int)$m[2], (int)$m[3]];
        return checkdate($mo, $da, $y) ? sprintf('%04d-%02d-%02d', $y, $mo, $da) : null;
    }
    return null;
}
function rcpt_date_to_roc(string $date): string {
    [$y, $m, $d] = array_map('intval', explode('-', substr($date, 0, 10)));
    return sprintf('%d/%02d/%02d', $y - 1911, $m, $d);
}

// 收據編號：物(115)09140001。流水號 1～9999；超過就是錯（一天一字軌不會開到一萬張，真遇到要停下來問）。
function rcpt_no(string $track, string $date, int $n): string {
    if (!in_array($track, RCPT_TRACKS, true)) throw new InvalidArgumentException('bad track');
    if ($n < 1 || $n > 9999) throw new RangeException('流水號超出 1～9999');
    [$y, $m, $d] = array_map('intval', explode('-', substr($date, 0, 10)));
    return sprintf('%s(%d)%02d%02d%04d', $track, $y - 1911, $m, $d, $n);
}

// 同字軌、同入庫日已用到的最大流水號（含作廢——作廢不重用）。
function rcpt_max_seq(PDO $d, string $track, string $date): int {
    $s = $d->prepare('SELECT COALESCE(MAX(dn.seq),0) FROM donation dn JOIN batch b ON b.id = dn.batch_id WHERE b.track = ? AND b.in_date = ?');
    $s->execute([$track, $date]);
    return (int)$s->fetchColumn();
}

// 配號：批次內依 row_no 順序，從同字軌同日的下一號接續。整批在一個交易內完成，失敗全部不動。
// 已配過號的批次不再配（回 false）；配完寫 first_no／last_no（給會計回填文中「報關單號」）。
// 食字軌收據要印品名與單位（單位查進貨明細 batch_item）。回傳有問題的列：[[row_no, 說明], ...]
// 不替使用者猜品名：缺的就擋下，請補名單重匯（大沈 R-itsu-1112-01：缺商品資料仍可配號、印出空白明細）
function rcpt_food_missing(PDO $d, int $batchId): array {
    $s = $d->prepare("SELECT dn.row_no, dn.product, bi.unit FROM donation dn
        LEFT JOIN batch_item bi ON bi.batch_id = dn.batch_id AND bi.name = dn.product
        WHERE dn.batch_id = ? ORDER BY dn.row_no");
    $s->execute([$batchId]);
    $out = [];
    foreach ($s->fetchAll(PDO::FETCH_ASSOC) as $r) {
        if (trim((string)$r['product']) === '') $out[] = [(int)$r['row_no'], '缺品名'];
        elseif (trim((string)$r['unit']) === '') $out[] = [(int)$r['row_no'], '品名「' . $r['product'] . '」不在進貨明細，對不到單位'];
    }
    return $out;
}

function rcpt_food_missing_text(array $miss): string {
    $parts = array_map(fn($m) => "第 {$m[0]} 列{$m[1]}", array_slice($miss, 0, 5));
    return '食字軌收據要印品名與單位，有 ' . count($miss) . ' 列不完整（' . implode('；', $parts) . (count($miss) > 5 ? '…' : '')
         . '）。請在名單補上「商品名稱」欄（品名要和進貨明細相同），或補齊進貨明細的品名與單位，再重新匯入';
}

function rcpt_assign(PDO $d, int $batchId, string $who): array {
    $d->beginTransaction();
    try {
        $b = $d->prepare('SELECT * FROM batch WHERE id = ? FOR UPDATE');
        $b->execute([$batchId]);
        $batch = $b->fetch(PDO::FETCH_ASSOC);
        if (!$batch) throw new RuntimeException('找不到批次');
        if ($batch['status'] !== 'draft') throw new RuntimeException('這個批次已配號，不能重配');
        // 同字軌同日的批次互相鎖住，避免兩人同時配號拿到同一段
        $d->prepare('SELECT pg_advisory_xact_lock(hashtext(?))')->execute([$batch['track'] . $batch['in_date']]);
        $rows = $d->prepare('SELECT id FROM donation WHERE batch_id = ? ORDER BY row_no');
        $rows->execute([$batchId]);
        $ids = $rows->fetchAll(PDO::FETCH_COLUMN);
        if (!$ids) throw new RuntimeException('批次沒有任何明細');
        $inb = rcpt_dup_in_batch($d, $batchId);
        if ($inb) throw new RuntimeException('名單裡有 ' . count($inb) . ' 個訂單編號重複出現（' . implode('、', array_slice(array_keys($inb), 0, 5)) . (count($inb) > 5 ? '…' : '') . '），同一筆訂單只能開一張收據，請整理名單後重新匯入');
        // 業務單位 11/12 選（乙）：訂單編號已在別批開過收據的，一律擋下不能開——整批不配號，要先把那幾筆從名單拿掉
        $on = $d->prepare("SELECT order_no FROM donation WHERE batch_id = ? AND order_no <> ''");
        $on->execute([$batchId]);
        $dup = rcpt_dup_orders($d, $on->fetchAll(PDO::FETCH_COLUMN), $batchId);
        if ($dup) throw new RuntimeException('有 ' . count($dup) . ' 筆訂單編號已經開過收據（' . implode('、', array_slice(array_map(fn($v) => $v[1], $dup), 0, 5)) . (count($dup) > 5 ? '…' : '') . '），請把它們從名單拿掉、重新匯入後再配號');
        if ($batch['track'] === '食' && ($miss = rcpt_food_missing($d, $batchId))) throw new RuntimeException(rcpt_food_missing_text($miss));
        $start = rcpt_max_seq($d, $batch['track'], $batch['in_date']) + 1;
        if ($start + count($ids) - 1 > 9999) throw new RangeException('這一天的流水號會超過 9999，請先確認');
        $u = $d->prepare('UPDATE donation SET seq = ?, receipt_no = ?, updated_by = ?, updated_at = now() WHERE id = ?');
        try {
            foreach ($ids as $i => $id) $u->execute([$start + $i, rcpt_no($batch['track'], $batch['in_date'], $start + $i), $who, $id]);
        } catch (PDOException $e) {   // 唯一索引 donation_order_issued：別的批次同時配號搶先開了同一訂單
            if (($e->errorInfo[0] ?? '') === '23505') throw new RuntimeException('有訂單編號剛被別的批次開了收據，這一批沒有配號，請重新整理後檢查');
            throw $e;
        }
        $first = rcpt_no($batch['track'], $batch['in_date'], $start);
        $last = rcpt_no($batch['track'], $batch['in_date'], $start + count($ids) - 1);
        $d->prepare("UPDATE batch SET status = 'numbered', first_no = ?, last_no = ?, updated_at = now() WHERE id = ?")->execute([$first, $last, $batchId]);
        rcpt_audit($d, $who, 'assign', $batchId, count($ids) . " 筆 {$first}～{$last}");
        $d->commit();
        return ['count' => count($ids), 'first' => $first, 'last' => $last, 'range' => rcpt_range_text($first, $last)];
    } catch (Throwable $e) {
        $d->rollBack();
        throw $e;
    }
}

// 回填文中「報關單號」的字串：物(115)09140001~5089（與業務單位現行寫法相同）
function rcpt_range_text(string $first, string $last): string {
    return $first === $last ? $first : $first . '~' . substr($last, -4);
}

// 訂單編號重複檢查（業務單位 11/12：「系統需要檢核訂單編號是否已經開立過收據，免得會重複開立收據」）。
// 傳入一批訂單編號，回傳已在「其他批次」開過收據（已配號）且未作廢的：order_no => [batch_id, receipt_no, po_no]
// 只算已開立的（大沈 P2：兩個草稿互相擋、又顯示「已開過」卻沒有收據號）；草稿之間的重複在配號時由唯一索引擋。
function rcpt_dup_orders(PDO $d, array $orderNos, ?int $exceptBatch = null): array {
    $orderNos = array_values(array_unique(array_filter(array_map('trim', $orderNos), 'strlen')));
    if (!$orderNos) return [];
    $out = [];
    foreach (array_chunk($orderNos, 500) as $chunk) {
        $in = implode(',', array_fill(0, count($chunk), '?'));
        $s = $d->prepare("SELECT dn.order_no, dn.batch_id, dn.receipt_no, b.po_no FROM donation dn JOIN batch b ON b.id = dn.batch_id
                          WHERE dn.order_no IN ($in) AND NOT dn.void AND dn.receipt_no IS NOT NULL" . ($exceptBatch ? ' AND dn.batch_id <> ?' : ''));
        $s->execute($exceptBatch ? array_merge($chunk, [$exceptBatch]) : $chunk);
        foreach ($s as $r) $out[$r['order_no']] = [(int)$r['batch_id'], $r['receipt_no'], $r['po_no']];
    }
    return $out;
}
