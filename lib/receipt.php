// 規則來源：業務單位 11/11 建置說明＋11/12 細節確認：
//   ・一張文中「進貨單」＝一個批次，對應一段連續收據編號（11/12 更正：不是入庫單；臨時捐物可先開收據、進貨單號後補）
//   ・收據編號＝字軌(民國年)＋收貨月日＋4 碼流水號（收貨日期＝進貨單上的收貨日），例 物(115)09140001；同字軌同入庫日從 0001 起、跨批次接續
//   ・清單每一筆都配號（不寄發的也佔號）；配號後鎖定，作廢保留不重用
// 🔴 捐物人姓名、電話、地址只存資料庫（schema receipt），不寫進紀錄檔、不進 GitHub。
require_once __DIR__ . '/db.php';

const RCPT_TRACKS = ['物', '食'];
const RCPT_SOURCES = ['ibon' => '物', 'i預購' => '物', '家庭雲端' => '食', '個人' => '食', '企業團體' => '食'];
const RCPT_ROLES = ['edit', 'view'];

function rcpt_db(): PDO {
    $d = itdb('receipt');
    static $ready = [];
    $key = spl_object_id($d);
    if (isset($ready[$key])) return $d;
    $d->exec(<<<SQL
CREATE TABLE IF NOT EXISTS users (
  email text PRIMARY KEY, role text NOT NULL CHECK (role IN ('edit','view')), note text NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS settings (k text PRIMARY KEY, v text NOT NULL);
CREATE TABLE IF NOT EXISTS batch (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source text NOT NULL, track text NOT NULL CHECK (track IN ('物','食')),
  po_no text UNIQUE, in_date date NOT NULL,   -- 文中進貨單號（可先開收據、後補；空值不擋）；in_date＝進貨單收貨日期
  supplier_code text NOT NULL DEFAULT '', supplier_name text NOT NULL DEFAULT '',
  set_price int, handler text NOT NULL DEFAULT '', contents text NOT NULL DEFAULT '', letter text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','numbered')),
  first_no text, last_no text,
  created_by text NOT NULL, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS batch_item (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id bigint NOT NULL REFERENCES batch(id) ON DELETE CASCADE,
  code text NOT NULL DEFAULT '', name text NOT NULL, qty numeric NOT NULL DEFAULT 0, unit text NOT NULL DEFAULT '', price numeric);
CREATE TABLE IF NOT EXISTS donation (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id bigint NOT NULL REFERENCES batch(id) ON DELETE CASCADE,
  row_no int NOT NULL, seq int, receipt_no text UNIQUE,
  order_no text NOT NULL DEFAULT '', name text NOT NULL DEFAULT '', mobile text NOT NULL DEFAULT '', phone text NOT NULL DEFAULT '',
  raw_addr text NOT NULL DEFAULT '', zip text NOT NULL DEFAULT '', city text NOT NULL DEFAULT '', address text NOT NULL DEFAULT '',
  product text NOT NULL DEFAULT '', qty int NOT NULL DEFAULT 0,
  send boolean NOT NULL DEFAULT true, check_note text NOT NULL DEFAULT '', dup_note text NOT NULL DEFAULT '', tax_id text NOT NULL DEFAULT '',
  void boolean NOT NULL DEFAULT false,
  updated_by text NOT NULL DEFAULT '', updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (batch_id, row_no));
CREATE INDEX IF NOT EXISTS donation_order_no ON donation (order_no) WHERE order_no <> '';
ALTER TABLE donation ADD COLUMN IF NOT EXISTS mailed_on date;   -- 寄出日期（業務單位 11/12：要記錄哪一天寄出收據）
CREATE TABLE IF NOT EXISTS print_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id bigint NOT NULL, donation_id bigint, kind text NOT NULL, count int NOT NULL DEFAULT 1,
  by_email text NOT NULL, at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  by_email text NOT NULL, at timestamptz NOT NULL DEFAULT now(), action text NOT NULL, batch_id bigint, detail text NOT NULL DEFAULT '');
SQL);
    $ready[$key] = true;
    return $d;
}

// 權限：edit＝開收據（建批次、匯入、配號、列印、改資料）；view＝查詢與看收據（客服、助理會計）。
// 名單在 users 表（由資訊部維護）；不在名單的人一律看不到——資料含捐物人個資。
function rcpt_role(PDO $d, string $email): ?string {
    $s = $d->prepare('SELECT role FROM users WHERE email = ?');
    $s->execute([strtolower($email)]);
    $r = $s->fetchColumn();
    return $r === false ? null : $r;
}

function rcpt_audit(PDO $d, string $who, string $action, ?int $batch = null, string $detail = ''): void {
    $d->prepare('INSERT INTO audit (by_email, action, batch_id, detail) VALUES (?,?,?,?)')->execute([$who, $action, $batch, $detail]);
}

// 民國年月日字串 115/09/14 ↔ 西元 date。接受 115/9/14、115-09-14、1150914。不合法回 null。
function rcpt_roc_to_date(string $s): ?string {
    $s = trim($s);
    if (preg_match('/^(\d{2,3})[\/\-.](\d{1,2})[\/\-.](\d{1,2})$/', $s, $m) || preg_match('/^(\d{3})(\d{2})(\d{2})$/', $s, $m)) {
        [$y, $mo, $da] = [(int)$m[1] + 1911, (int)$m[2], (int)$m[3]];
        return checkdate($mo, $da, $y) ? sprintf('%04d-%02d-%02d', $y, $mo, $da) : null;
    }
    return null;
}
function rcpt_date_to_roc(string $date): string {
    [$y, $m, $d] = array_map('intval', explode('-', substr($date, 0, 10)));
    return sprintf('%d/%02d/%02d', $y - 1911, $m, $d);
}

// 收據編號：物(115)09140001。流水號 1～9999；超過就是錯（一天一字軌不會開到一萬張，真遇到要停下來問）。
function rcpt_no(string $track, string $date, int $n): string {
    if (!in_array($track, RCPT_TRACKS, true)) throw new InvalidArgumentException('bad track');
    if ($n < 1 || $n > 9999) throw new RangeException('流水號超出 1～9999');
    [$y, $m, $d] = array_map('intval', explode('-', substr($date, 0, 10)));
    return sprintf('%s(%d)%02d%02d%04d', $track, $y - 1911, $m, $d, $n);
}

// 同字軌、同入庫日已用到的最大流水號（含作廢——作廢不重用）。
function rcpt_max_seq(PDO $d, string $track, string $date): int {
    $s = $d->prepare('SELECT COALESCE(MAX(dn.seq),0) FROM donation dn JOIN batch b ON b.id = dn.batch_id WHERE b.track = ? AND b.in_date = ?');
    $s->execute([$track, $date]);
    return (int)$s->fetchColumn();
}

// 配號：批次內依 row_no 順序，從同字軌同日的下一號接續。整批在一個交易內完成，失敗全部不動。
// 已配過號的批次不再配（回 false）；配完寫 first_no／last_no（給會計回填文中「報關單號」）。
function rcpt_assign(PDO $d, int $batchId, string $who): array {
    $d->beginTransaction();
    try {
        $b = $d->prepare('SELECT * FROM batch WHERE id = ? FOR UPDATE');
        $b->execute([$batchId]);
        $batch = $b->fetch(PDO::FETCH_ASSOC);
        if (!$batch) throw new RuntimeException('找不到批次');
        if ($batch['status'] !== 'draft') throw new RuntimeException('這個批次已配號，不能重配');
        // 同字軌同日的批次互相鎖住，避免兩人同時配號拿到同一段
        $d->prepare('SELECT pg_advisory_xact_lock(hashtext(?))')->execute([$batch['track'] . $batch['in_date']]);
        $rows = $d->prepare('SELECT id FROM donation WHERE batch_id = ? ORDER BY row_no');
        $rows->execute([$batchId]);
        $ids = $rows->fetchAll(PDO::FETCH_COLUMN);
        if (!$ids) throw new RuntimeException('批次沒有任何明細');
        // 業務單位 11/12 選（乙）：訂單編號已在別批開過收據的，一律擋下不能開——整批不配號，要先把那幾筆從名單拿掉
        $on = $d->prepare("SELECT order_no FROM donation WHERE batch_id = ? AND order_no <> ''");
        $on->execute([$batchId]);
        $dup = rcpt_dup_orders($d, $on->fetchAll(PDO::FETCH_COLUMN), $batchId);
        if ($dup) throw new RuntimeException('有 ' . count($dup) . ' 筆訂單編號已經開過收據（' . implode('、', array_slice(array_map(fn($v) => $v[1], $dup), 0, 5)) . (count($dup) > 5 ? '…' : '') . '），請把它們從名單拿掉、重新匯入後再配號');
        $start = rcpt_max_seq($d, $batch['track'], $batch['in_date']) + 1;
        if ($start + count($ids) - 1 > 9999) throw new RangeException('這一天的流水號會超過 9999，請先確認');
        $u = $d->prepare('UPDATE donation SET seq = ?, receipt_no = ?, updated_by = ?, updated_at = now() WHERE id = ?');
        foreach ($ids as $i => $id) $u->execute([$start + $i, rcpt_no($batch['track'], $batch['in_date'], $start + $i), $who, $id]);
        $first = rcpt_no($batch['track'], $batch['in_date'], $start);
        $last = rcpt_no($batch['track'], $batch['in_date'], $start + count($ids) - 1);
        $d->prepare("UPDATE batch SET status = 'numbered', first_no = ?, last_no = ?, updated_at = now() WHERE id = ?")->execute([$first, $last, $batchId]);
        rcpt_audit($d, $who, 'assign', $batchId, count($ids) . " 筆 {$first}～{$last}");
        $d->commit();
        return ['count' => count($ids), 'first' => $first, 'last' => $last, 'range' => rcpt_range_text($first, $last)];
    } catch (Throwable $e) {
        $d->rollBack();
        throw $e;
    }
}

// 回填文中「報關單號」的字串：物(115)09140001~5089（與業務單位現行寫法相同）
function rcpt_range_text(string $first, string $last): string {
    return $first === $last ? $first : $first . '~' . substr($last, -4);
}

// 訂單編號重複檢查（業務單位 11/12：「系統需要檢核訂單編號是否已經開立過收據，免得會重複開立收據」）。
// 傳入一批訂單編號，回傳已在「其他批次」出現且未作廢的：order_no => [batch_id, receipt_no, po_no]
function rcpt_dup_orders(PDO $d, array $orderNos, ?int $exceptBatch = null): array {
    $orderNos = array_values(array_unique(array_filter(array_map('trim', $orderNos), 'strlen')));
    if (!$orderNos) return [];
    $out = [];
    foreach (array_chunk($orderNos, 500) as $chunk) {
        $in = implode(',', array_fill(0, count($chunk), '?'));
        $s = $d->prepare("SELECT dn.order_no, dn.batch_id, dn.receipt_no, b.po_no FROM donation dn JOIN batch b ON b.id = dn.batch_id
                          WHERE dn.order_no IN ($in) AND NOT dn.void" . ($exceptBatch ? ' AND dn.batch_id <> ?' : ''));
        $s->execute($exceptBatch ? array_merge($chunk, [$exceptBatch]) : $chunk);
        foreach ($s as $r) $out[$r['order_no']] = [(int)$r['batch_id'], $r['receipt_no'], $r['po_no']];
    }
    return $out;
}
