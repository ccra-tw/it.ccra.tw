const RCPT_OPT_KINDS = ['source' => '來源', 'supplier' => '供應商', 'set_price' => '套餐每套金額'];

/** 選項清單。$activeOnly＝只要啟用中的（給選單用）；設定頁要全部 */
function rcpt_options(PDO $d, string $kind, bool $activeOnly = true): array {
    $s = $d->prepare('SELECT * FROM option_item WHERE kind = ?' . ($activeOnly ? ' AND active' : '') . ' ORDER BY active DESC, sort, id');
    $s->execute([$kind]);
    return $s->fetchAll(PDO::FETCH_ASSOC);
}

/** 檢查並正規化一筆選項輸入；錯誤丟 RuntimeException（訊息給使用者看） */
function rcpt_option_clean(string $kind, string $code, string $name, string $extra): array {
    if (!isset(RCPT_OPT_KINDS[$kind])) throw new RuntimeException('不認得的設定類別');
    $code = trim(mb_convert_kana($code, 'as', 'UTF-8')); $name = trim($name); $extra = trim($extra);
    if ($kind === 'source') {
        if ($code === '' || mb_strlen($code) > 20) throw new RuntimeException('來源名稱請填 1～20 字');
        if (!in_array($extra, ['物', '食'], true)) throw new RuntimeException('來源要選字軌：物 或 食');
        $name = '';
    } elseif ($kind === 'supplier') {
        if ($code === '' || mb_strlen($code) > 20) throw new RuntimeException('供應商編號請填 1～20 字');
        if ($name === '' || mb_strlen($name) > 40) throw new RuntimeException('供應商名稱請填 1～40 字');
        $extra = '';
    } else {
        if (!preg_match('/^\d{1,6}$/', $code) || (int)$code <= 0) throw new RuntimeException('套餐每套金額請填正整數（例：360）');
        $code = (string)(int)$code; $name = ''; $extra = '';
    }
    return [$code, $name, $extra];
}

