// 戰情室網頁推播（Web Push，RFC 8291 aes128gcm＋RFC 8292 VAPID）。
// 熊哥 2026-10-13 TG：「戰情室可以有網頁推播，有異常狀況可以即時通知」，範圍：斷線、資安事件、新申請單。
// 只用 PHP 內建 openssl／curl，不裝套件。VAPID 金鑰第一次用到時產生在 STATE_DIR/vapid.json（www-data 600，不進 GitHub）；
// ⚠️ 金鑰換掉，所有人的訂閱都會失效，要各自重新按「開啟通知」。
// 訂閱存 PostgreSQL schema push（表 subs），推送失敗回 404／410 代表對方已取消，直接刪除。
require_once __DIR__ . '/db.php';
if (!defined('STATE_DIR')) define('STATE_DIR', '/var/lib/it-ccra');
const VAPID_SUB = 'mailto:ituncle@ccra.org.tw';

function wp_b64u($s) { return rtrim(strtr(base64_encode($s), '+/', '-_'), '='); }
function wp_unb64u($s) { return base64_decode(strtr($s, '-_', '+/') . str_repeat('=', (4 - strlen($s) % 4) % 4)); }

function push_db(): PDO {
    $d = itdb('push');
    $d->exec('CREATE TABLE IF NOT EXISTS subs (endpoint TEXT PRIMARY KEY, p256dh TEXT, auth TEXT, email TEXT, ua TEXT,
              created_at TEXT, last_ok_at TEXT, fails INTEGER DEFAULT 0)');
    $d->exec('CREATE TABLE IF NOT EXISTS log (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at TEXT, kind TEXT,
              title TEXT, body TEXT, url TEXT, n_ok INTEGER, n_fail INTEGER)');
    return $d;
}

// 回傳 ['public' => base64url(65 bytes), 'pem' => 私鑰 PEM]
function vapid_keys(): array {
    $f = STATE_DIR . '/vapid.json';
    if (is_file($f)) return json_decode(file_get_contents($f), true);
    $k = openssl_pkey_new(['curve_name' => 'prime256v1', 'private_key_type' => OPENSSL_KEYTYPE_EC]);
    openssl_pkey_export($k, $pem);
    $d = openssl_pkey_get_details($k)['ec'];
    $v = ['public' => wp_b64u("\x04" . str_pad($d['x'], 32, "\0", STR_PAD_LEFT) . str_pad($d['y'], 32, "\0", STR_PAD_LEFT)),
          'pem' => $pem, 'created_at' => date('c')];
    $tmp = $f . '.tmp';
    file_put_contents($tmp, json_encode($v));
    chmod($tmp, 0600);
    rename($tmp, $f);
    return $v;
}

// 65 bytes 未壓縮公鑰 → OpenSSL 可讀的公鑰
function wp_pub_from_raw($raw) {
    $der = hex2bin('3059301306072a8648ce3d020106082a8648ce3d030107034200') . $raw;
    return openssl_pkey_get_public("-----BEGIN PUBLIC KEY-----\n" . chunk_split(base64_encode($der), 64, "\n") . "-----END PUBLIC KEY-----\n");
}

// openssl_sign 回 DER，JWT ES256 要 r||s 各 32 bytes
function wp_der2raw($der) {
    $o = 2; if (ord($der[1]) & 0x80) $o += ord($der[1]) & 0x7f;
    $out = '';
    for ($i = 0; $i < 2; $i++) {
        $len = ord($der[$o + 1]); $n = substr($der, $o + 2, $len); $o += 2 + $len;
        $out .= str_pad(ltrim($n, "\0"), 32, "\0", STR_PAD_LEFT);
    }
    return $out;
}

// $eph／$salt 只給測試用（RFC 8291 附錄 A 的固定值），正式呼叫一律隨機產生
function wp_encrypt($payload, $p256dh, $auth, $eph = null, $salt = null) {
    $ua = wp_unb64u($p256dh); $authSecret = wp_unb64u($auth);
    if (strlen($ua) !== 65 || strlen($authSecret) !== 16) throw new InvalidArgumentException('bad subscription keys');
    $eph = $eph ?: openssl_pkey_new(['curve_name' => 'prime256v1', 'private_key_type' => OPENSSL_KEYTYPE_EC]);
    $e = openssl_pkey_get_details($eph)['ec'];
    $as = "\x04" . str_pad($e['x'], 32, "\0", STR_PAD_LEFT) . str_pad($e['y'], 32, "\0", STR_PAD_LEFT);
    $shared = openssl_pkey_derive(wp_pub_from_raw($ua), $eph, 32);
    if ($shared === false) throw new RuntimeException('ECDH failed');
    $ikm = hash_hkdf('sha256', $shared, 32, "WebPush: info\0" . $ua . $as, $authSecret);
    $salt = $salt ?? random_bytes(16);
    $cek = hash_hkdf('sha256', $ikm, 16, "Content-Encoding: aes128gcm\0", $salt);
    $nonce = hash_hkdf('sha256', $ikm, 12, "Content-Encoding: nonce\0", $salt);
    $ct = openssl_encrypt($payload . "\x02", 'aes-128-gcm', $cek, OPENSSL_RAW_DATA, $nonce, $tag);
    return $salt . pack('N', 4096) . chr(65) . $as . $ct . $tag;
}

function wp_vapid_header($endpoint) {
    $v = vapid_keys();
    $u = parse_url($endpoint);
    $h = wp_b64u(json_encode(['typ' => 'JWT', 'alg' => 'ES256']));
    $c = wp_b64u(json_encode(['aud' => $u['scheme'] . '://' . $u['host'], 'exp' => time() + 12 * 3600, 'sub' => VAPID_SUB]));
    openssl_sign("$h.$c", $sig, $v['pem'], OPENSSL_ALGO_SHA256);
    return 'vapid t=' . "$h.$c." . wp_b64u(wp_der2raw($sig)) . ', k=' . $v['public'];
}

// 送給一筆訂閱，回傳 HTTP 狀態碼（0 = 連線失敗）
function wp_send_one(array $sub, string $payload, int $ttl = 3600): int {
    $body = wp_encrypt($payload, $sub['p256dh'], $sub['auth']);
    $ch = curl_init($sub['endpoint']);
    curl_setopt_array($ch, [CURLOPT_POST => true, CURLOPT_POSTFIELDS => $body, CURLOPT_RETURNTRANSFER => true, CURLOPT_TIMEOUT => 15,
        CURLOPT_HTTPHEADER => ['Content-Type: application/octet-stream', 'Content-Encoding: aes128gcm', "TTL: $ttl",
            'Urgency: high', 'Authorization: ' . wp_vapid_header($sub['endpoint'])]]);
    curl_exec($ch);
    $code = (int)curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
    return $code;
}

// 推給所有訂閱（或指定 email 的訂閱）。回傳 [成功數, 失敗數]。
// $msg：title, body, url（點通知開哪頁）, tag（同 tag 的新通知會取代舊的，例如同一台主機）
function push_send(array $msg, string $kind = 'manual', ?string $email = null): array {
    $d = push_db();
    $s = $email ? $d->prepare('SELECT * FROM subs WHERE email = ?') : $d->prepare('SELECT * FROM subs');
    $s->execute($email ? [strtolower($email)] : []);
    $payload = json_encode(['title' => $msg['title'] ?? '戰情室', 'body' => $msg['body'] ?? '', 'url' => $msg['url'] ?? '/ops/',
        'tag' => $msg['tag'] ?? null], JSON_UNESCAPED_UNICODE);
    $ok = $fail = 0;
    foreach ($s->fetchAll(PDO::FETCH_ASSOC) as $sub) {
        try { $code = wp_send_one($sub, $payload); } catch (Throwable $e) { error_log('webpush: ' . $e->getMessage()); $code = 0; }
        if ($code >= 200 && $code < 300) {
            $ok++;
            $d->prepare('UPDATE subs SET last_ok_at = ?, fails = 0 WHERE endpoint = ?')->execute([date('c'), $sub['endpoint']]);
        } elseif ($code === 404 || $code === 410) {          // 對方已取消訂閱或過期
            $fail++;
            $d->prepare('DELETE FROM subs WHERE endpoint = ?')->execute([$sub['endpoint']]);
        } else {
            $fail++;
            error_log("webpush: HTTP $code for {$sub['email']}");
            $d->prepare('UPDATE subs SET fails = fails + 1 WHERE endpoint = ?')->execute([$sub['endpoint']]);
        }
    }
    $d->prepare('INSERT INTO log (at, kind, title, body, url, n_ok, n_fail) VALUES (?,?,?,?,?,?,?)')
      ->execute([date('c'), $kind, $msg['title'] ?? '', $msg['body'] ?? '', $msg['url'] ?? '', $ok, $fail]);
    return [$ok, $fail];
}
